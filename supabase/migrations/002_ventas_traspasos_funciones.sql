------------------------------------------------------------------ traspasos
create table if not exists public.traspasos (
  id              bigint generated by default as identity primary key,
  origen_id       bigint not null references public.sucursales(id),
  destino_id      bigint not null references public.sucursales(id),
  estado          text not null default 'pendiente'
                    check (estado in ('pendiente','enviado','recibido','cancelado')),
  responsable     text not null check (length(trim(responsable)) > 0),
  notas           text,
  fecha           timestamptz not null default now(),
  enviado_at      timestamptz,
  recibido_at     timestamptz,
  cancelado_at    timestamptz,
  idempotency_key uuid unique,
  check (origen_id <> destino_id)
);

create table if not exists public.traspaso_items (
  id          bigint generated by default as identity primary key,
  traspaso_id bigint not null references public.traspasos(id) on delete cascade,
  producto_id bigint not null,
  talla_id    bigint not null,
  color_id    bigint not null,
  cantidad    integer not null check (cantidad > 0)
);
create index if not exists traspaso_items_tr_idx on public.traspaso_items (traspaso_id);

------------------------------------------------------------------ helper de stock
-- Unica puerta de escritura al inventario. Atomica: el UPDATE con guarda evita negativos
-- incluso con operaciones concurrentes.
create or replace function public._mover_stock(
  p_sucursal bigint, p_producto bigint, p_talla bigint, p_color bigint,
  p_delta integer, p_tipo text, p_ref_tipo text, p_ref_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_delta = 0 then raise exception 'Cantidad invalida'; end if;

  if p_delta > 0 then
    insert into public.inventario (sucursal_id, producto_id, talla_id, color_id, cantidad)
    values (p_sucursal, p_producto, p_talla, p_color, p_delta)
    on conflict (sucursal_id, producto_id, talla_id, color_id)
    do update set cantidad = public.inventario.cantidad + excluded.cantidad, updated_at = now();
  else
    update public.inventario
       set cantidad = cantidad + p_delta, updated_at = now()
     where sucursal_id = p_sucursal and producto_id = p_producto
       and talla_id = p_talla and color_id = p_color
       and cantidad >= -p_delta;
    if not found then
      raise exception 'Stock insuficiente en la sucursal para producto %, talla %, color %',
        p_producto, p_talla, p_color using errcode = 'P0001';
    end if;
  end if;

  insert into public.movimientos_inventario
    (tipo, sucursal_id, producto_id, talla_id, color_id, cantidad, ref_tipo, ref_id)
  values (p_tipo, p_sucursal, p_producto, p_talla, p_color, p_delta, p_ref_tipo, p_ref_id);
end $$;
revoke all on function public._mover_stock(bigint,bigint,bigint,bigint,integer,text,text,bigint) from public, anon, authenticated;

------------------------------------------------------------------ ingreso de stock
create or replace function public.agregar_stock(
  p_sucursal bigint, p_producto bigint, p_talla bigint, p_color bigint, p_cantidad integer)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor a 0'; end if;
  perform public._mover_stock(p_sucursal, p_producto, p_talla, p_color, p_cantidad, 'ingreso', null, null);
end $$;

------------------------------------------------------------------ ventas
create or replace function public.crear_venta(
  p_sucursal bigint, p_metodo_pago text, p_modalidad text,
  p_departamento text, p_ciudad text, p_provincia text, p_municipio text,
  p_direccion text, p_agencia text, p_referencias text,
  p_cliente_nombre text, p_cliente_telefono text,
  p_items jsonb, p_key uuid)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_id bigint; v_total numeric := 0; it jsonb;
  v_cant integer; v_precio numeric;
  v_deptos text[] := array['Beni','Chuquisaca','Cochabamba','La Paz','Oruro','Pando','Potosí','Santa Cruz','Tarija'];
begin
  if p_key is null then raise exception 'Falta la clave de idempotencia'; end if;
  select id into v_id from public.ventas where idempotency_key = p_key;
  if v_id is not null then return v_id; end if;

  if not exists (select 1 from public.sucursales where id = p_sucursal and estado) then
    raise exception 'Sucursal invalida'; end if;
  if p_metodo_pago is null or p_metodo_pago not in ('QR','efectivo') then
    raise exception 'Metodo de pago invalido'; end if;
  if p_modalidad is null or p_modalidad not in ('entrega_directa','envio','envio_interprovincial') then
    raise exception 'Modalidad invalida'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La venta no tiene productos'; end if;

  if p_modalidad = 'envio' then
    if p_departamento is null or not (p_departamento = any (v_deptos)) then
      raise exception 'Departamento invalido'; end if;
    if coalesce(trim(p_ciudad),'') = '' or coalesce(trim(p_direccion),'') = '' then
      raise exception 'Ciudad/localidad y direccion son obligatorias para envios'; end if;
  elsif p_modalidad = 'envio_interprovincial' then
    if coalesce(trim(p_departamento),'') = '' or coalesce(trim(p_provincia),'') = ''
       or coalesce(trim(p_municipio),'') = '' or coalesce(trim(p_direccion),'') = ''
       or coalesce(trim(p_agencia),'') = '' then
      raise exception 'Envio interprovincial: departamento, provincia, municipio, direccion y agencia son obligatorios';
    end if;
  end if;

  insert into public.ventas (total, sucursal_id, metodo_pago, modalidad, departamento, ciudad,
      provincia, municipio, direccion, agencia_transporte, referencias,
      cliente_nombre, cliente_telefono, estado, idempotency_key)
  values (0, p_sucursal, p_metodo_pago, p_modalidad,
      case when p_modalidad = 'entrega_directa' then null else trim(p_departamento) end,
      case when p_modalidad = 'envio' then trim(p_ciudad) else null end,
      case when p_modalidad = 'envio_interprovincial' then trim(p_provincia) end,
      case when p_modalidad = 'envio_interprovincial' then trim(p_municipio) end,
      case when p_modalidad = 'entrega_directa' then null else trim(p_direccion) end,
      case when p_modalidad = 'envio_interprovincial' then trim(p_agencia) end,
      nullif(trim(coalesce(p_referencias,'')),''),
      nullif(trim(coalesce(p_cliente_nombre,'')),''), nullif(trim(coalesce(p_cliente_telefono,'')),''),
      'completada', p_key)
  on conflict (idempotency_key) where idempotency_key is not null do nothing
  returning id into v_id;

  if v_id is null then  -- otra peticion con la misma clave gano la carrera
    select id into v_id from public.ventas where idempotency_key = p_key;
    return v_id;
  end if;

  for it in select * from jsonb_array_elements(p_items) loop
    v_cant   := (it->>'cantidad')::integer;
    v_precio := (it->>'precio_unitario')::numeric;
    if v_cant is null or v_cant <= 0 then raise exception 'Cantidad invalida'; end if;
    if v_precio is null or v_precio < 0 then raise exception 'Precio invalido'; end if;

    perform public._mover_stock(p_sucursal, (it->>'producto_id')::bigint, (it->>'talla_id')::bigint,
      (it->>'color_id')::bigint, -v_cant, 'venta', 'venta', v_id);

    insert into public.detalle_venta (venta_id, producto_id, talla_id, color_id, cantidad, precio_unitario, subtotal)
    values (v_id, (it->>'producto_id')::bigint, (it->>'talla_id')::bigint, (it->>'color_id')::bigint,
            v_cant, v_precio, v_cant * v_precio);
    v_total := v_total + v_cant * v_precio;
  end loop;

  update public.ventas set total = v_total where id = v_id;
  return v_id;
end $$;

create or replace function public.cancelar_venta(p_venta bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare v public.ventas; d record;
begin
  if coalesce(trim(p_motivo),'') = '' then raise exception 'El motivo es obligatorio'; end if;
  select * into v from public.ventas where id = p_venta for update;
  if not found then raise exception 'Venta no encontrada'; end if;
  if v.estado = 'cancelada' then raise exception 'La venta ya esta cancelada'; end if;

  for d in select * from public.detalle_venta where venta_id = p_venta loop
    perform public._mover_stock(v.sucursal_id, d.producto_id, d.talla_id, d.color_id,
      d.cantidad, 'anulacion_venta', 'venta', p_venta);
  end loop;
  update public.ventas set estado = 'cancelada', motivo_cancelacion = trim(p_motivo), cancelada_at = now()
   where id = p_venta;
end $$;

------------------------------------------------------------------ traspasos
create or replace function public.crear_traspaso(
  p_origen bigint, p_destino bigint, p_responsable text, p_notas text, p_items jsonb, p_key uuid)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint; it jsonb;
begin
  if p_key is null then raise exception 'Falta la clave de idempotencia'; end if;
  select id into v_id from public.traspasos where idempotency_key = p_key;
  if v_id is not null then return v_id; end if;

  if p_origen = p_destino then raise exception 'Origen y destino deben ser distintos'; end if;
  if (select count(*) from public.sucursales where id in (p_origen, p_destino) and estado) <> 2 then
    raise exception 'Sucursal invalida'; end if;
  if coalesce(trim(p_responsable),'') = '' then raise exception 'El responsable es obligatorio'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El traspaso no tiene productos'; end if;

  insert into public.traspasos (origen_id, destino_id, responsable, notas, idempotency_key)
  values (p_origen, p_destino, trim(p_responsable), nullif(trim(coalesce(p_notas,'')),''), p_key)
  on conflict (idempotency_key) do nothing returning id into v_id;
  if v_id is null then
    select id into v_id from public.traspasos where idempotency_key = p_key; return v_id;
  end if;

  for it in select * from jsonb_array_elements(p_items) loop
    if (it->>'cantidad')::integer is null or (it->>'cantidad')::integer <= 0 then
      raise exception 'Cantidad invalida'; end if;
    insert into public.traspaso_items (traspaso_id, producto_id, talla_id, color_id, cantidad)
    values (v_id, (it->>'producto_id')::bigint, (it->>'talla_id')::bigint,
            (it->>'color_id')::bigint, (it->>'cantidad')::integer);
  end loop;
  return v_id;
end $$;

-- pendiente -> enviado : descuenta del origen
create or replace function public.despachar_traspaso(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare t public.traspasos; i record;
begin
  select * into t from public.traspasos where id = p_id for update;
  if not found then raise exception 'Traspaso no encontrado'; end if;
  if t.estado <> 'pendiente' then
    raise exception 'Solo se puede despachar un traspaso pendiente (estado actual: %)', t.estado; end if;
  for i in select * from public.traspaso_items where traspaso_id = p_id loop
    perform public._mover_stock(t.origen_id, i.producto_id, i.talla_id, i.color_id,
      -i.cantidad, 'traspaso_salida', 'traspaso', p_id);
  end loop;
  update public.traspasos set estado = 'enviado', enviado_at = now() where id = p_id;
end $$;

-- enviado -> recibido : suma al destino
create or replace function public.recibir_traspaso(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare t public.traspasos; i record;
begin
  select * into t from public.traspasos where id = p_id for update;
  if not found then raise exception 'Traspaso no encontrado'; end if;
  if t.estado <> 'enviado' then
    raise exception 'Solo se puede recibir un traspaso enviado (estado actual: %)', t.estado; end if;
  for i in select * from public.traspaso_items where traspaso_id = p_id loop
    perform public._mover_stock(t.destino_id, i.producto_id, i.talla_id, i.color_id,
      i.cantidad, 'traspaso_entrada', 'traspaso', p_id);
  end loop;
  update public.traspasos set estado = 'recibido', recibido_at = now() where id = p_id;
end $$;

-- pendiente -> cancelado (sin stock) | enviado -> cancelado (devuelve al origen). Recibido no se cancela.
create or replace function public.cancelar_traspaso(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare t public.traspasos; i record;
begin
  select * into t from public.traspasos where id = p_id for update;
  if not found then raise exception 'Traspaso no encontrado'; end if;
  if t.estado in ('recibido','cancelado') then
    raise exception 'No se puede cancelar un traspaso %', t.estado; end if;
  if t.estado = 'enviado' then
    for i in select * from public.traspaso_items where traspaso_id = p_id loop
      perform public._mover_stock(t.origen_id, i.producto_id, i.talla_id, i.color_id,
        i.cantidad, 'traspaso_cancelado', 'traspaso', p_id);
    end loop;
  end if;
  update public.traspasos set estado = 'cancelado', cancelado_at = now() where id = p_id;
end $$;

grant execute on function
  public.agregar_stock(bigint,bigint,bigint,bigint,integer),
  public.crear_venta(bigint,text,text,text,text,text,text,text,text,text,text,text,jsonb,uuid),
  public.cancelar_venta(bigint,text),
  public.crear_traspaso(bigint,bigint,text,text,jsonb,uuid),
  public.despachar_traspaso(bigint), public.recibir_traspaso(bigint), public.cancelar_traspaso(bigint)
to anon, authenticated;

commit;
