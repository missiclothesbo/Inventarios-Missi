  id          bigint generated by default as identity primary key,
  fecha       timestamptz not null default now(),
  tipo        text not null check (tipo in
                ('venta','anulacion_venta','traspaso_salida','traspaso_entrada',
                 'traspaso_cancelado','ingreso')),
  sucursal_id bigint not null references public.sucursales(id),
  producto_id bigint not null,
  talla_id    bigint not null,
  color_id    bigint not null,
  cantidad    integer not null check (cantidad <> 0),   -- con signo: + entra, - sale
  ref_tipo    text,                                      -- 'venta' | 'traspaso'
  ref_id      bigint
);
