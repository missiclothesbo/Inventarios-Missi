-- 001_sucursales_y_catalogo.sql
-- Incremental e idempotente. NO borra datos. Todo el stock actual pasa a Cochabamba.
begin;

create table if not exists public.sucursales (
  id         bigint generated by default as identity primary key,
  codigo     text not null unique,
  nombre     text not null unique,
  es_central boolean not null default false,
  estado     boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.sucursales (codigo, nombre, es_central) values
  ('CBBA', 'MISSI Cochabamba', true),
  ('SCZ',  'MISSI Santa Cruz',  false)
on conflict (codigo) do nothing;

-- inventario: sucursal_id (existentes -> Cochabamba)
alter table public.inventario add column if not exists sucursal_id bigint references public.sucursales(id);
update public.inventario
   set sucursal_id = (select id from public.sucursales where codigo = 'CBBA')
 where sucursal_id is null;
alter table public.inventario alter column sucursal_id set not null;

-- Reemplaza la unicidad (producto,talla,color) por (sucursal,producto,talla,color)
do $$
declare r record;
begin
  for r in
    select c.conname
      from pg_constraint c
     where c.conrelid = 'public.inventario'::regclass and c.contype = 'u'
       and (select array_agg(a.attname::text order by a.attname)
              from unnest(c.conkey) k join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k)
           = array['color_id','producto_id','talla_id']
  loop
    execute format('alter table public.inventario drop constraint %I', r.conname);
  end loop;
end $$;

-- indices unicos "sueltos" equivalentes (si existieran en vez de constraint)
do $$
declare r record;
begin
  for r in
    select i.indexrelid::regclass::text as idx
      from pg_index i
     where i.indrelid = 'public.inventario'::regclass and i.indisunique and not i.indisprimary
       and not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
       and (select array_agg(a.attname::text order by a.attname)
              from unnest(i.indkey) k join pg_attribute a on a.attrelid = i.indrelid and a.attnum = k)
           = array['color_id','producto_id','talla_id']
  loop
    execute format('drop index %s', r.idx);
  end loop;
end $$;

create unique index if not exists inventario_sucursal_variante_uq
  on public.inventario (sucursal_id, producto_id, talla_id, color_id);

do $$ begin
  alter table public.inventario add constraint inventario_cantidad_no_negativa check (cantidad >= 0) not valid;
exception when duplicate_object then null; end $$;

-- Catalogo nuevo (no toca S, M, G, GG, GGG)
insert into public.tallas (nombre, estado)
select v, true from (values ('36'),('38'),('40'),('42'),('44')) t(v)
 where not exists (select 1 from public.tallas x where x.nombre = t.v);

insert into public.productos (nombre, estado)
select 'Short sastrero', true
 where not exists (select 1 from public.productos x where lower(x.nombre) = 'short sastrero');

commit;
