await db.exec("alter default privileges in schema public grant all on tables to anon, authenticated; alter default privileges in schema public grant execute on functions to anon, authenticated; grant all on all tables in schema public to anon, authenticated; grant execute on all functions in schema public to anon, authenticated;");
for (const f of ["001_sucursales_y_catalogo.sql", "002_ventas_traspasos_funciones.sql", "003_reportes_y_rls.sql", "004_bloquear_escritura_directa.sql"]) {
  await db.exec(fs.readFileSync(dir + f, "utf8")); console.log("aplicada", f);
}
// idempotencia de migraciones
for (const f of ["001_sucursales_y_catalogo.sql", "002_ventas_traspasos_funciones.sql", "003_reportes_y_rls.sql"]) await db.exec(fs.readFileSync(dir + f, "utf8"));
